/**
 * roadmap-types.ts — Shared types and validation for roadmap.json.
 *
 * Used by: generate-docs.ts, verify-roadmap.ts
 * Single source of truth for Feature interfaces.
 */

/** Valid verify directive types. Keep in sync with VALID_VERIFY_TYPES in
 *  packages/opencode/src/cli/cmd/roadmap.ts. "reviewer" is a legacy alias for
 *  "overseer"; both are accepted so old roadmaps keep verifying. */
export const VALID_VERIFY_TYPES = ["file", "grep", "test", "typecheck", "cmd", "agent", "overseer", "reviewer"] as const;
export type VerifyType = typeof VALID_VERIFY_TYPES[number];

/** Valid feature statuses */
export const VALID_STATUSES = ["done", "planned", "in_progress", "backlog", "abandoned", "blocked"] as const;
export type FeatureStatus = typeof VALID_STATUSES[number];

export interface VerifyDef {
  type: string;
  path?: string;
  pattern?: string;
  command?: string;
}

/** An acceptance criterion for overseer verification */
export interface AcceptanceCriterion {
  /** Human-readable description of what must work */
  check: string;
  /** How to verify (test, grep, manual) */
  verify: string;
  /** If true, blocks DONE when not met */
  critical: boolean;
}

export interface Feature {
  id: string;
  title: string;
  status: string;
  version?: string;
  changelog?: string;
  notes?: string;
  blocker?: string;
  subfeatures?: string[];
  verify?: VerifyDef[];
  /** Acceptance criteria for overseer deep verification. Generated by architect at promotion time. */
  acceptance_criteria?: AcceptanceCriterion[];
}

export interface Version {
  tag: string;
  date?: string;
  description: string;
}

export interface RoadmapData {
  versions: Version[];
  features: Feature[];
}

/** Version sort: v0.6.1 → [0,6,1,1], v0.10.0 → [0,10,0,1], v1.0.0-alpha → [1,0,0,-2], v1.0.0-rc → [1,0,0,-1], v1.0.0 → [1,0,0,1] */
export function parseVersionTag(tag: string): number[] {
  const clean = tag.startsWith("v") ? tag.slice(1) : tag;
  // Split pre-release suffix
  const suffixMatch = clean.match(/^(\d+\.\d+\.\d+)[-.]?(alpha|rc|beta)?$/i);
  if (!suffixMatch) {
    // Fallback: just split by dots
    return clean.split(".").map(p => {
      const n = parseInt(p, 10);
      return isNaN(n) ? 0 : n;
    });
  }
  const main = suffixMatch[1].split(".").map(p => parseInt(p, 10));
  const suffix = suffixMatch[2]?.toLowerCase();
  // Suffix order: alpha < rc < release (no suffix = release)
  if (suffix === "alpha") main.push(-2);
  else if (suffix === "beta") main.push(-1);
  else if (suffix === "rc") main.push(0);
  else main.push(1); // release
  
  return main;
}

export function sortVersions(versions: Version[]): Version[] {
  return [...versions].sort((a, b) => {
    const va = parseVersionTag(a.tag);
    const vb = parseVersionTag(b.tag);
    for (let i = 0; i < Math.max(va.length, vb.length); i++) {
      const diff = (va[i] ?? 0) - (vb[i] ?? 0);
      if (diff !== 0) return diff;
    }
    return 0;
  });
}

/**
 * Validate roadmap.json structure. Returns list of error messages.
 * Empty array = no errors.
 */
export function validateRoadmap(data: RoadmapData): string[] {
  const errors: string[] = [];

  // Check versions
  if (!Array.isArray(data.versions) || data.versions.length === 0) {
    errors.push("versions must be a non-empty array");
  }

  const versionTags = new Set((data.versions ?? []).map(v => v.tag));
  const seenIds = new Set<string>();

  for (let i = 0; i < (data.features ?? []).length; i++) {
    const f = data.features[i];
    const loc = `features[${i}] (id="${f.id}")`;

    // 1. ID must be unique
    if (!f.id) {
      errors.push(`${loc}: missing id`);
      continue;
    }
    if (seenIds.has(f.id)) {
      errors.push(`${loc}: duplicate id "${f.id}"`);
    }
    seenIds.add(f.id);

    // 2. Status must be valid
    if (!VALID_STATUSES.includes(f.status as any)) {
      errors.push(`${loc}: invalid status "${f.status}". Valid: ${VALID_STATUSES.join(", ")}`);
    }

    // 3. If version is specified, it must exist in versions list
    if (f.version && !versionTags.has(f.version)) {
      errors.push(`${loc}: version "${f.version}" not found in versions. Existing: ${[...versionTags].join(", ")}`);
    }

    // 4. Verify directives validation — overseer requires acceptance_criteria
    if (f.verify && f.verify.some(v => v.type === "overseer")) {
      if (!f.acceptance_criteria || f.acceptance_criteria.length === 0) {
        errors.push(`${loc}: "overseer" verify type requires "acceptance_criteria"`);
      }
    }

    // 5. Acceptance criteria validation
    if (f.acceptance_criteria) {
      for (let j = 0; j < f.acceptance_criteria.length; j++) {
        const ac = f.acceptance_criteria[j];
        const acloc = `${loc}.acceptance_criteria[${j}]`;
        if (!ac.check) {
          errors.push(`${acloc}: missing "check" field`);
        }
        if (typeof ac.critical !== "boolean") {
          errors.push(`${acloc}: "critical" must be boolean`);
        }
      }
    }

    // 6. Verify directives validation
    if (f.verify) {
      if (!Array.isArray(f.verify)) {
        errors.push(`${loc}: verify must be an array`);
      } else {
        for (let j = 0; j < f.verify.length; j++) {
          const v = f.verify[j];
          const vloc = `${loc}.verify[${j}]`;
          if (!VALID_VERIFY_TYPES.includes(v.type as any)) {
            errors.push(`${vloc}: invalid verify type "${v.type}". Valid: ${VALID_VERIFY_TYPES.join(", ")}`);
          }
          if ((v.type === "file" || v.type === "grep" || v.type === "test") && !v.path) {
            errors.push(`${vloc}: "${v.type}" requires a "path" field`);
          }
          if (v.type === "grep" && !v.pattern) {
            errors.push(`${vloc}: "grep" requires a "pattern" field`);
          }
          if (v.type === "cmd" && !v.command && !v.path) {
            errors.push(`${vloc}: "cmd" requires a "command" or "path" field`);
          }
          // overseer type derives attestation path from feature version + title, no fields needed
        }
      }
    }
  }

  return errors;
}
